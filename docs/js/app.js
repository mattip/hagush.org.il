const PORTRAITS_DIR = "portraits/";
// Optional tab to open on a deep-link when the URL carries no ?tab (ask.html
// sets data-default-tab="interview" so ?id=<id> opens straight to the interview).
const DEFAULT_TAB = document.currentScript.dataset.defaultTab || "";

const popup = document.getElementById("popup");
let allPeople = [];
let popupHistory = []; // stack of people for back navigation
let interviewIndex = []; // interviews/index.json entries (for ask.html)

// ── Bootstrap ────────────────────────────────────────────────────
const dataReady = Promise.all([
  fetch("candidates.json", { cache: "no-cache" }).then((r) => r.json()),
  // Manifest of parsed interviews, regenerated by add_interview.html.
  fetch("interviews/index.json", { cache: "no-cache" }).then((r) => (r.ok ? r.json() : [])).catch(() => []),
])
  .then(([people, index]) => {
    // index.json: array of objects {id, name, date, source} or legacy array of strings
    interviewIndex = index;
    allPeople = people.filter((p) => !p.hidden);
    // Open popup from URL: ?id=emily_m or ?name=אמיר
    // (We don't rewrite the address bar here — doing so changes how the
    // browser resolves relative URLs on the page, breaking nav links and
    // image src paths.)
    syncPopupToUrl("init");
    // Also resync on back/forward — otherwise the DOM keeps whatever popup
    // was last drawn, even when the URL says a different candidate.
    window.addEventListener("popstate", (e) => {
      syncPopupToUrl("popstate");
    });
    // pageshow also fires on bfcache restore (back from another origin / tab).
    // popstate doesn't always fire in that case, so this is a belt-and-braces.
    window.addEventListener("pageshow", (e) => {
      if (e.persisted) syncPopupToUrl("pageshow-bfcache");
    });
  });

function syncPopupToUrl(reason) {
  if (!allPeople.length) {
    return;
  }
  const params    = new URLSearchParams(window.location.search);
  const idParam   = params.get("id");
  const nameParam = params.get("name");
  console.log("syncPopupToUrl:", reason, { idParam, nameParam });
  if (!(idParam || nameParam)) {
    if (popup.classList.contains("open")) {
      closePopup();
    return;
   }
  }
  const match = allPeople.find((p) =>
    idParam ? p.id === idParam : p.name === nameParam,
  );
  if (!match) {
    console.warn("syncPopupToUrl: no match for", idParam || nameParam);
    return;
  }
  if (popup.classList.contains("open") && popup.dataset.personId === match.id) {
    return;
  }
  openPopup(match, false);
}

