async function initPopupTabs(candidateId) {
  const tabBar     = document.getElementById("popupTabs");
  const profileP   = document.getElementById("panelProfile");
  const interviewP = document.getElementById("panelInterview");

  console.log("initPopupTabs:", candidateId);

  // Reset to profile tab
  tabBar.querySelectorAll(".popup-tab").forEach(t =>
    t.classList.toggle("active", t.dataset.tab === "profile")
  );
  profileP.style.display = "";
  interviewP.style.display = "none";

  // Fetch interview data. Distinguish "no interview" (404 — expected, stay
  // quiet) from "interview exists but is broken" (parse/HTTP error — log loudly
  // so a malformed docs/interviews/<id>.json doesn't just silently vanish).
  const url = INTERVIEWS_DIR + candidateId + ".json";
  let data = null;
  try {
    const res = await fetch(url, { cache: "no-cache" });
    if (res.ok) {
      try {
        data = await res.json();
      } catch (err) {
        console.error(
          `Interview file ${url} is invalid JSON — interview tab hidden. Fix the file:`,
          err.message,
        );
      }
    } else if (res.status !== 404) {
      console.warn(`Interview file ${url} failed to load: HTTP ${res.status}`);
    }
  } catch (err) {
    console.warn(`Interview file ${url} could not be fetched:`, err.message);
  }

  if (data && Array.isArray(data.messages) && data.messages.length > 0) {
    tabBar.style.display = "flex";
    tabBar.querySelector('[data-tab="interview"]').textContent =
      data.source === "document" ? "עכשיו שואלות!" : "ראיון וואטסאפ";
    try {
      renderChat(data);
    } catch (err) {
      console.error(`Failed to render interview for "${data.candidate_id}":`, err);
    }

    // Switch to interview tab if ?tab=interview is in URL, or if this page
    // defaults to it (ask.html via data-default-tab) and the URL sets no ?tab.
    const requestedTab = new URLSearchParams(window.location.search).get("tab") || DEFAULT_TAB;
    if (requestedTab === "interview") {
      tabBar.querySelectorAll(".popup-tab").forEach(t =>
        t.classList.toggle("active", t.dataset.tab === "interview")
      );
      profileP.style.display = "none";
      interviewP.style.display = "";
      interviewP.scrollTop = 0;
    }
  } else {
    tabBar.style.display = "none";
  }
}

// Turn https:// URLs inside interview text into safe clickable links; the rest
// stays as plain text nodes. Returns an array of nodes/strings for elem().
function linkifyText(text) {
  const s = String(text ?? "");
  const nodes = [];
  const re = /https:\/\/[^\s]+/g;
  let last = 0, m;
  while ((m = re.exec(s)) !== null) {
    let url = m[0];
    const trail = url.match(/[.,;:!?)\]]+$/);   // keep trailing punctuation out of the link
    const tail = trail ? trail[0] : "";
    if (tail) url = url.slice(0, -tail.length);
    if (m.index > last) nodes.push(s.slice(last, m.index));
    nodes.push(elem("a", { class: "iv-link", href: url, target: "_blank", rel: "noreferrer" }, url));
    if (tail) nodes.push(tail);
    last = m.index + m[0].length;
  }
  if (last < s.length) nodes.push(s.slice(last));
  return nodes;
}

function renderChat(data) {
  const wrap = document.getElementById("ivAccordion");
  document.getElementById("ivLoading").style.display = "none";

  const imgBase = INTERVIEWS_DIR + data.candidate_id + "/";

  // role: "question" → interviewer bubble (green), "answer" → candidate (white).
  // A content item is a string (text bubble) or a media dict {type, file|url}.
  function renderBubble(p, role, ctx) {
    const cls = role === "question" ? "iv-bubble iv-bubble-iv" : "iv-bubble iv-bubble-cd";

    if (p && typeof p === "object") {
      const src = p.url || (p.file ? imgBase + p.file : null);
      if ((p.type === "image" || p.type === "video" || p.type === "audio") && !src) {
        console.error(
          `Interview "${data.candidate_id}" ${ctx}: ${p.type} item has no "file" or "url" — skipped. Item:`, p);
        return elem("div", { class: `${cls} iv-bubble-broken` }, "⚠️ מדיה חסרה");
      }
      if (p.type === "image") return elem("div", { class: cls },
        elem("img", { class: "iv-bubble-img", src, alt: "", loading: "lazy" }));
      if (p.type === "video") return elem("div", { class: cls },
        elem("div", { class: "iv-video-wrap" },
          elem("video", { class: "iv-video", src, playsinline: "", preload: "metadata" }),
          elem("button", { class: "iv-video-play", "aria-label": "נגן" }, "▶")));
      if (p.type === "audio") return elem("div", { class: cls },
        elem("audio", { class: "iv-audio", controls: "", src, preload: "metadata" }));
      if (p.type === "text")  return elem("div", { class: cls }, ...linkifyText(p.text));
      console.error(
        `Interview "${data.candidate_id}" ${ctx}: unrecognized item (need a string or {type:image|video|audio|text}) — skipped. Item:`, p);
      return elem("div", { class: `${cls} iv-bubble-broken` }, "⚠️ תוכן לא נתמך");
    }

    return elem("div", { class: cls }, ...linkifyText(p));
  }

  const chat = elem("div", { class: "iv-chat" });
  data.messages.forEach((msg, i) => {
    const role = "question" in msg ? "question" : "answer";
    const parts = msg[role];
    if (!Array.isArray(parts)) {
      console.error(
        `Interview "${data.candidate_id}" message #${i}: expected a "question" or "answer" array — skipped. Message:`, msg);
      return;
    }
    parts.forEach((p) => chat.append(renderBubble(p, role, `message #${i}`)));
  });

  wrap.replaceChildren(chat);

  // Video play/pause
  wrap.addEventListener("click", (e) => {
    const playBtn = e.target.closest(".iv-video-play");
    if (!playBtn) return;
    const video = playBtn.parentElement.querySelector("video");
    if (video.paused) {
      video.play();
      playBtn.classList.add("playing");
    } else {
      video.pause();
      playBtn.classList.remove("playing");
    }
    video.onended = () => playBtn.classList.remove("playing");
  });
}


